// Versions returns the payload version manifest: payload struct name
// (e.g. "ToolCall", "LLMRequest") mapped to the `<Name>Version` constant
// the running code stamps into `_schema_version`. It covers every payload
// that carries a version constant.
//
// The map is a fresh copy on every call, so a caller cannot mutate the
// package's view. Consumers pin the subset they read in one table test and
// get a single failure naming every payload that moved; see "Consumer-side
// pinning" in the package documentation.
func Versions() map[string]int {
	return maps.Clone(versions)
}
